ErpRole? getRoleById(List<ErpRole> roles, String roleId) {
  for (final role in roles) {
    if (role.id == roleId) return role;
  }
  return null;
}

bool canAccess(List<ErpRole> roles, String roleId, String permission) {
  if (permission.isEmpty) return true;
  final role = getRoleById(roles, roleId);
  return role?.permissions.contains(permission) ?? false;
}
